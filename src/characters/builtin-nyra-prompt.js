/** Current ta seed plus the previously shipped 她 seed. */
export function officialNyraSeedTexts() {
  const current = BUILTIN_NYRA_CHARACTER_PROMPT.trim();
  return Object.freeze([current, current.replace(/\bta\b/g, "她")]);
}

export function isOfficialNyraSeedText(text) {
  return officialNyraSeedTexts().includes(String(text || "").trim());
}

/**
 * Adapt only the untouched official seed. Once a user edits the prompt, the
 * edited text is authoritative and is returned byte-for-byte.
 * The seed itself uses ta. After the user chooses gender: female → 她, male → 他.
 */
export function compileBuiltinNyraPrompt(prompt, {
  isBuiltin = false,
  name = BUILTIN_NYRA_NAME,
  genderIdentity = "",
  pronouns = [],
} = {}) {
  const source = String(prompt || "").trim();
  if (!isBuiltin || !isOfficialNyraSeedText(source)) return source;
  const formalName = String(name || "").trim() || BUILTIN_NYRA_NAME;
  return adaptAuthoredNyraThirdPerson(
    source.replace(/\bNyra\b/g, () => formalName),
    { name: formalName, genderIdentity, pronouns },
  );
}
