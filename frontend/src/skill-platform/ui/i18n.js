export function tx(key, localeOrVars, maybeVars) {
  let locale = getLocale();
  /** @type {Record<string, string|number>} */
  let vars = {};
  if (typeof localeOrVars === "string" && PACKS[localeOrVars]) {
    locale = localeOrVars;
    vars = maybeVars || {};
  } else if (localeOrVars && typeof localeOrVars === "object") {
    vars = localeOrVars;
  } else if (typeof localeOrVars === "string") {
    locale = localeOrVars;
  }
  const hit = PACKS[locale]?.[key];
  let text = hit;
  if (text == null && locale !== "en") text = PACKS.en?.[key];
  if (text == null) return key;
  return String(text).replace(/\{(\w+)\}/g, (_, k) => (
    vars[k] == null ? `{${k}}` : String(vars[k])
  ));
}

