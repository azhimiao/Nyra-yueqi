/**
 * Build src/skill-platform/play-packs-data.js from skills-play/* folders.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { surfaceForPlayPack } from "../src/skill-platform/play-surfaces.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const playRoot = path.join(root, "skills-play");
const outFile = path.join(root, "src", "skill-platform", "play-packs-data.js");

function walk(dir, base = dir) {
  /** @type {Record<string, string>} */
  const files = {};
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      Object.assign(files, walk(full, base));
      continue;
    }
    if (!/\.(md|txt|json|ya?ml)$/i.test(ent.name)) continue;
    const rel = path.relative(base, full).split(path.sep).join("/");
    files[rel] = fs.readFileSync(full, "utf8");
  }
  return files;
}

const packs = [];
for (const name of fs.readdirSync(playRoot)) {
  const dir = path.join(playRoot, name);
  if (!fs.statSync(dir).isDirectory()) continue;
  if (!fs.existsSync(path.join(dir, "SKILL.md"))) continue;
  packs.push({
    id: name,
    label: name,
    surface: surfaceForPlayPack(name),
    files: walk(dir),
  });
}

const body = `/** Auto-generated by scripts/build-play-packs.mjs — do not edit. */
export const PLAY_PACKS = ${JSON.stringify(packs, null, 2)};
`;
fs.writeFileSync(outFile, body, "utf8");
console.log(`wrote ${packs.length} packs → ${path.relative(root, outFile)}`);
